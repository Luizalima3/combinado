CREATE TABLE combinado_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combinado_id BIGINT NOT NULL REFERENCES combinados(id),
    autor_id BIGINT NOT NULL REFERENCES tb_usuarios(id),
    autor_nome VARCHAR(255) NOT NULL,
    acao VARCHAR(255) NOT NULL,
    ocorrido_em TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_combinado_historico_timeline
    ON combinado_historico(combinado_id, ocorrido_em, id);