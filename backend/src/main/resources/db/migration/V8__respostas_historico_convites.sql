-- Antes desta migration, Hibernate criava convites. Permite bancos novos e existentes.
CREATE TABLE IF NOT EXISTS convites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    combinado_id BIGINT NOT NULL REFERENCES combinados(id),
    remetente_id BIGINT NOT NULL REFERENCES tb_usuarios(id),
    destinatario_id BIGINT NOT NULL REFERENCES tb_usuarios(id),
    status VARCHAR(255) NOT NULL,
    mensagem VARCHAR(255),
    data_envio TIMESTAMP NOT NULL
);
ALTER TABLE convites ADD COLUMN data_resposta TIMESTAMP WITH TIME ZONE;
CREATE TABLE convite_historico (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    convite_id BIGINT NOT NULL REFERENCES convites(id),
    autor_id BIGINT NOT NULL REFERENCES tb_usuarios(id),
    autor_nome VARCHAR(255) NOT NULL,
    acao VARCHAR(255) NOT NULL,
    ocorrido_em TIMESTAMP WITH TIME ZONE NOT NULL,
    UNIQUE (convite_id, acao)
);
CREATE INDEX idx_convites_destinatario_combinado ON convites(combinado_id, destinatario_id);
CREATE INDEX idx_convite_historico_timeline ON convite_historico(convite_id, ocorrido_em, id);
-- Datas de respostas legadas não são inventadas: só novas ações geram histórico.
