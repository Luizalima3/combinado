CREATE TABLE tarefas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao TEXT NOT NULL,
    combinado_id BIGINT NOT NULL REFERENCES combinados(id)
);
CREATE INDEX idx_tarefas_combinado ON tarefas(combinado_id);
CREATE TABLE tarefa_responsaveis (
    tarefa_id BIGINT NOT NULL REFERENCES tarefas(id),
    usuario_id BIGINT NOT NULL REFERENCES tb_usuarios(id),
    PRIMARY KEY (tarefa_id, usuario_id)
);
CREATE INDEX idx_tarefa_responsaveis_usuario ON tarefa_responsaveis(usuario_id);
