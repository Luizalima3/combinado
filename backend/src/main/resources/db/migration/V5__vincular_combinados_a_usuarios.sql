-- Até V4, Hibernate criava esta tabela. Garante a criação em bancos novos antes dos vínculos.
CREATE TABLE IF NOT EXISTS combinados (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(255) NOT NULL,
    descricao TEXT,
    categoria VARCHAR(255) NOT NULL,
    data_prazo DATE,
    criador_nome VARCHAR(255) NOT NULL,
    participante_nome VARCHAR(255) NOT NULL,
    responsabilidades TEXT,
    status VARCHAR(255) NOT NULL,
    aceito_em TIMESTAMP,
    recusado_em TIMESTAMP,
    criado_em TIMESTAMP
);

ALTER TABLE combinados ADD COLUMN criador_id BIGINT REFERENCES tb_usuarios(id);

CREATE TABLE combinado_participantes (
    combinado_id BIGINT NOT NULL REFERENCES combinados(id),
    usuario_id BIGINT NOT NULL REFERENCES tb_usuarios(id),
    PRIMARY KEY (combinado_id, usuario_id)
);

CREATE INDEX idx_combinados_criador ON combinados(criador_id);
CREATE INDEX idx_combinado_participantes_usuario ON combinado_participantes(usuario_id);
